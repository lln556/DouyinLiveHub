#!/usr/bin/env python3
"""Download Douyin official web emoji assets and generate static manifest/map."""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import json
import os
from pathlib import Path
import re
import socket
import sys
import tempfile
import urllib.parse

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import config  # noqa: E402
from crawler.fetcher import DouyinLiveWebFetcher, generateMsToken  # noqa: E402

EMOJI_LIST_API = 'https://www.douyin.com/aweme/v1/web/emoji/list/'
DEFAULT_EMOJI_DIR = PROJECT_ROOT / 'data' / 'emoji_img'
DEFAULT_MAP_JS_PATH = PROJECT_ROOT / 'static' / 'js' / 'emoji-map.js'


def detect_image_ext(data: bytes) -> str:
    """Detect the true image extension from file magic bytes."""
    if len(data) >= 12 and data[:4] == b'RIFF' and data[8:12] == b'WEBP':
        return 'webp'
    if data.startswith(b'\x89PNG\r\n\x1a\n'):
        return 'png'
    if data[:6] in (b'GIF87a', b'GIF89a'):
        return 'gif'
    if data[:3] == b'\xff\xd8\xff':
        return 'jpg'
    return 'png'


def sanitize_stem(origin_uri: str, fallback_key: str) -> str:
    """Create a safe ASCII filename stem from origin_uri or fallback_key."""
    raw_stem = Path(str(origin_uri or '')).stem
    stem = re.sub(r'[^A-Za-z0-9_-]', '_', raw_stem).strip('_')
    if stem:
        return stem
    return hashlib.md5(str(fallback_key).encode('utf-8')).hexdigest()[:12]


def _atomic_write_bytes(target: Path, data: bytes) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    temp_path = None
    try:
        with tempfile.NamedTemporaryFile(dir=target.parent, prefix=f'.{target.name}.', delete=False) as tmp:
            temp_path = tmp.name
            tmp.write(data)
            tmp.flush()
            os.fsync(tmp.fileno())
        os.chmod(temp_path, 0o644)
        os.replace(temp_path, target)
    finally:
        if temp_path and os.path.exists(temp_path):
            os.unlink(temp_path)


def _atomic_write_text(target: Path, text: str) -> None:
    _atomic_write_bytes(target, text.encode('utf-8'))


def fetch_official_emoji_list(fetcher: DouyinLiveWebFetcher) -> tuple[object, list[dict]]:
    """Fetch official web emoji metadata list using fetcher's session and a_bogus signer."""
    params = {
        'device_platform': 'webapp',
        'aid': '6383',
        'channel': 'channel_pc_web',
        'version_code': '170400',
        'version_name': '17.4.0',
        'cookie_enabled': 'true',
        'platform': 'PC',
        'msToken': generateMsToken(),
    }
    abogus = fetcher.get_a_bogus(params)
    url = f"{EMOJI_LIST_API}?{urllib.parse.urlencode(params)}&a_bogus={urllib.parse.quote(str(abogus))}"
    headers = fetcher._headers_with_cookie({'ttwid': fetcher.ttwid})
    headers['Referer'] = 'https://www.douyin.com/'
    response = fetcher.session.get(url, headers=headers, timeout=fetcher.request_timeout)
    response.raise_for_status()
    payload = response.json()
    emoji_list = payload.get('emoji_list') or []
    return payload.get('version'), emoji_list


def _download_emoji_bytes(url_list: list[str], proxies: dict | None, user_agent: str) -> bytes:
    import requests

    last_error = None
    headers = {'User-Agent': user_agent, 'Referer': 'https://www.douyin.com/'}
    for url in url_list:
        if not url:
            continue
        try:
            resp = requests.get(url, headers=headers, proxies=proxies or None, timeout=(5, 15))
            resp.raise_for_status()
            if resp.content:
                return resp.content
        except Exception as exc:
            last_error = exc
    raise RuntimeError(f'无法下载表情图片: {last_error}')


def build_emoji_map_js(mapping: dict[str, str]) -> str:
    """Render static/js/emoji-map.js defining window.DOUYIN_EMOJI_MAP."""
    ordered = {key: mapping[key] for key in sorted(mapping)}
    serialized = json.dumps(ordered, ensure_ascii=False, indent=2)
    return (
        '/* Auto-generated by utils/download_emoji.py */\n'
        f'window.DOUYIN_EMOJI_MAP = Object.freeze({serialized});\n'
    )


def _can_resolve_configured_proxy() -> bool:
    if not config.PROXY_ENABLED:
        return False
    try:
        socket.getaddrinfo(config.PROXY_HOST, config.PROXY_PORT)
        return True
    except OSError:
        return False


def sync_official_emojis(
    emoji_dir: Path = DEFAULT_EMOJI_DIR,
    map_js_path: Path = DEFAULT_MAP_JS_PATH,
    force: bool = False,
    max_workers: int = 8,
    fetcher: DouyinLiveWebFetcher | None = None,
) -> dict[str, str]:
    """Download official Douyin emojis and write manifest.json and emoji-map.js."""
    emoji_dir = Path(emoji_dir)
    map_js_path = Path(map_js_path)
    emoji_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = emoji_dir / 'manifest.json'

    existing_map: dict[str, str] = {}
    if not force and manifest_path.exists():
        try:
            old_data = json.loads(manifest_path.read_text(encoding='utf-8'))
            if isinstance(old_data, dict) and isinstance(old_data.get('emojis'), dict):
                existing_map = {
                    str(k): str(v) for k, v in old_data['emojis'].items()
                    if isinstance(k, str) and isinstance(v, str)
                }
        except Exception:
            existing_map = {}

    owns_fetcher = fetcher is None
    if owns_fetcher:
        proxy_enabled = _can_resolve_configured_proxy()
        fetcher = DouyinLiveWebFetcher('0', proxy_enabled=proxy_enabled)
    try:
        version, emoji_list = fetch_official_emoji_list(fetcher)
        proxies = fetcher.proxies if getattr(fetcher, 'proxy_enabled', False) else None
        user_agent = fetcher.user_agent
    finally:
        if owns_fetcher:
            fetcher.close()

    if not emoji_list:
        raise RuntimeError('抖音表情接口返回空列表')

    mapping: dict[str, str] = {}
    used_stems: dict[str, str] = {}
    pending_tasks: list[tuple[str, str, list[str]]] = []

    for item in emoji_list:
        display_name = str(item.get('display_name') or '').strip()
        if not display_name:
            continue
        url_list = (item.get('emoji_url') or {}).get('url_list') or []
        stem = sanitize_stem(item.get('origin_uri') or '', display_name)
        owner = used_stems.get(stem)
        if owner is not None and owner != display_name:
            stem = f"{stem}_{hashlib.md5(display_name.encode('utf-8')).hexdigest()[:6]}"
        used_stems[stem] = display_name

        cached_file = existing_map.get(display_name)
        if not force and cached_file:
            cached_path = emoji_dir / cached_file
            if cached_path.is_file() and cached_path.stat().st_size > 0:
                mapping[display_name] = cached_file
                continue

        if url_list:
            pending_tasks.append((display_name, stem, list(url_list)))

    if pending_tasks:
        with ThreadPoolExecutor(max_workers=max(1, max_workers)) as pool:
            future_map = {
                pool.submit(_download_emoji_bytes, urls, proxies, user_agent): (display_name, stem)
                for display_name, stem, urls in pending_tasks
            }
            for future in as_completed(future_map):
                display_name, stem = future_map[future]
                raw_bytes = future.result()
                ext = detect_image_ext(raw_bytes)
                filename = f'{stem}.{ext}'
                _atomic_write_bytes(emoji_dir / filename, raw_bytes)
                mapping[display_name] = filename

    ordered_mapping = {key: mapping[key] for key in sorted(mapping)}
    manifest_payload = {
        'version': version,
        'count': len(ordered_mapping),
        'emojis': ordered_mapping,
    }
    _atomic_write_text(manifest_path, json.dumps(manifest_payload, ensure_ascii=False, indent=2) + '\n')
    _atomic_write_text(map_js_path, build_emoji_map_js(ordered_mapping))
    return ordered_mapping


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description='下载抖音官方 Web 端表情包并生成前端映射表')
    parser.add_argument('--force', action='store_true', help='忽略本地缓存，强制重新下载全部表情图片')
    args = parser.parse_args(argv)
    mapping = sync_official_emojis(force=args.force)
    print(f'✅ 已同步 {len(mapping)} 个抖音官方表情 -> {DEFAULT_EMOJI_DIR} & {DEFAULT_MAP_JS_PATH}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
