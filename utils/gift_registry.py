def lookup_gift_by_id(gift_id, overrides: dict | None = None) -> tuple[str, float] | None:
    """按官方 ID 查询名称和单价，优先采用调用方的礼物价格覆盖。"""
    if gift_id is None or isinstance(gift_id, bool):
        return None
    if isinstance(gift_id, int):
        gid = gift_id
    elif isinstance(gift_id, float):
        if not math.isfinite(gift_id) or not gift_id.is_integer():
            return None
        gid = int(gift_id)
    elif isinstance(gift_id, str) and gift_id.isascii() and gift_id.isdigit():
        try:
            gid = int(gift_id)
        except ValueError:
            return None
    else:
        return None
    if gid <= 0:
        return None
    entry = DOUYIN_GIFT_ID_CATALOG.get(gid)
    if entry is None:
        return None
    name, base_price = entry
    price = float(base_price)
    if isinstance(overrides, dict) and name in overrides:
        override_val = overrides[name]
        if (isinstance(override_val, (int, float)) and not isinstance(override_val, bool)
                and override_val >= 0 and math.isfinite(override_val)):
            price = float(override_val)
    return name, price


def resolve_diy_composite_gift(diy_raw, outer_name: str = '', overrides: dict | None = None,
                               max_name_len: int = 96) -> tuple[float, str] | None:
    """按盒内礼物 ID 和数量计价，并生成适合数据库字段的展示名称。"""
    if isinstance(diy_raw, str):
        if not diy_raw.strip():
            return None
        try:
            parsed = json.loads(diy_raw)
        except (ValueError, TypeError):
            return None
    else:
        parsed = diy_raw
    if isinstance(parsed, list):
        items_list = parsed
    elif isinstance(parsed, dict):
        candidates = [parsed.get('items'), parsed.get('diy_item_info'), parsed.get('list')]
        if isinstance(parsed.get('data'), dict):
            candidates.append(parsed['data'].get('items'))
        items_list = next((candidate for candidate in candidates if isinstance(candidate, list)), None)
        if items_list is None:
            return None
    else:
        return None

    composite_price = 0.0
    counts = OrderedDict()
    for item in items_list:
        if not isinstance(item, dict):
            continue
        values = item.get('values') if isinstance(item.get('values'), dict) else item
        raw_gid = values.get('gift_id') if values.get('gift_id') is not None else item.get('gift_id')
        raw_count = next((value for value in (values.get('count'), values.get('num'),
                                              values.get('gift_count'), item.get('count'), item.get('num'))
                          if value is not None), 1)
        if isinstance(raw_count, bool):
            continue
        if isinstance(raw_count, int):
            count = raw_count
        elif isinstance(raw_count, str) and raw_count.isascii() and raw_count.isdigit():
            try:
                count = int(raw_count)
            except ValueError:
                continue
        else:
            continue
        if count <= 0:
            continue

        resolved = lookup_gift_by_id(raw_gid, overrides=overrides)
        if resolved is not None:
            inner_name, unit_price = resolved
        else:
            unit_price = next((value for source in (values, item)
                               for key in ('real_diamond_count', 'buff_diamond_count', 'diamond_count')
                               if isinstance((value := source.get(key)), (int, float))
                               and not isinstance(value, bool) and math.isfinite(value) and value > 0), 0)
            inner_name = next((text.strip() for text in (values.get('gift_name'), values.get('name'),
                                                         item.get('gift_name'), item.get('name'))
                               if isinstance(text, str) and text.strip()), '')
            if (not inner_name and isinstance(raw_gid, (int, str))
                    and not isinstance(raw_gid, bool) and str(raw_gid).strip()):
                inner_name = f'礼物#{str(raw_gid).strip()}'
        if unit_price > 0 and math.isfinite(unit_price):
            composite_price += float(unit_price) * count
            if inner_name:
                counts[inner_name] = counts.get(inner_name, 0) + count
    if composite_price <= 0:
        return None

    inner_summary = '+'.join(f'{name}x{count}' if count > 1 else name
                             for name, count in counts.items())
    outer = outer_name.strip() if isinstance(outer_name, str) else ''
    if outer and inner_summary and outer != inner_summary:
        candidate = f'{outer}({inner_summary})'
    else:
        candidate = inner_summary or outer
    if max_name_len <= 1:
        candidate = candidate[:max(0, max_name_len)]
    elif len(candidate) > max_name_len:
        if outer and inner_summary and len(outer) + 3 < max_name_len:
            budget = max_name_len - len(outer) - 3
            candidate = f'{outer}({inner_summary[:budget]}…)'
        else:
            candidate = candidate[:max_name_len - 1] + '…'
    return float(composite_price), candidate
